export const translateValue = (value, language) => {
  if (!value) return value;
  const langTranslations = translations[language];
  if (!langTranslations) return value;

  // Normalize value for lookup (e.g., "Employee" -> "employee")
  const key = value.toLowerCase().replace(/\./g, '');
  
  if (langTranslations[key]) {
    return langTranslations[key];
  }

  // Handle common transliterations if not found in dictionary
  // (Simple example for demo names)
  if (language === 'gu') {
    if (value === 'Mashru Bhavya') return 'મશરૂ ભવ્ય';
    if (value === 'Employee User') return 'કર્મચારી વપરાશકર્તા';
    if (value === 'Hello') return 'હેલો';
    if (value === 'Arcs') return 'આર્કસ';
  }
  
  if (language === 'hi') {
    if (value === 'Mashru Bhavya') return 'मशरू भव्या';
    if (value === 'Employee User') return 'कर्मचारी उपयोगकर्ता';
    if (value === 'Hello') return 'हेलो';
    if (value === 'Arcs') return 'आर्क्स';
  }

  return value;
};
